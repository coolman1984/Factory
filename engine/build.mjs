// Bundle the engine modules into one plain script for an offline single-file page: dist/factory-engine.js.
// The page gets window.FactoryEngine; Node can require() the same file. No dependencies, no install.
// Module rules (checked here): single-line `import { ... } from "./x.js";`, and `export` only before function/class/const.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import vm from "node:vm";

const ORDER = ["units.js", "rng.js", "queue.js", "canon.js", "ledger.js", "routes.js", "world.js", "blueprint.js"];
const root = new URL("./src/", import.meta.url), names = [];
const parts = ORDER.map(file => {
  const src = readFileSync(new URL(file, root), "utf8").replace(/\r\n/g, "\n");
  const body = src.split("\n").map((line, i) => {
    if (/^\s*import\b/.test(line)) { if (!/^import \{[^}]*\} from "\.\/[a-z-]+\.js";$/.test(line)) throw new Error(`${file}:${i + 1}: unsupported import form`); return ""; }
    const m = /^export (function|class|const|let) ([A-Za-z_$][\w$]*)/.exec(line);
    if (m) { names.push(m[2]); return line.slice(7); }
    if (/^\s*export\b/.test(line)) throw new Error(`${file}:${i + 1}: unsupported export form`);
    return line;
  }).join("\n");
  return `/* ---- ${file} ---- */\n${body}`;
});
const dup = names.find((n, i) => names.indexOf(n) !== i); if (dup) throw new Error("duplicate export " + dup);
const version = /ENGINE_VERSION = "([^"]+)"/.exec(readFileSync(new URL("world.js", root), "utf8"))[1];
let code = `/* Factory Engine ${version}: deterministic simulation core (3D Factory repository, engine/). Generated by engine/build.mjs; do not edit. */\n(function (root) {\n"use strict";\n${parts.join("\n")}\nconst api = Object.freeze({ ${names.join(", ")} });\nif (typeof module !== "undefined" && module.exports) module.exports = api; else root.FactoryEngine = api;\n})(typeof globalThis !== "undefined" ? globalThis : this);\n`;
new vm.Script(code, { filename: "factory-engine.js" });   // syntax check
const ctx = { module: { exports: {} }, Math, JSON, Object, Array, Map, Set, Number, String, Error, Infinity, NaN, Symbol, WeakMap };
vm.runInNewContext(code, ctx); if (!ctx.module.exports.World) throw new Error("bundle does not export World");
mkdirSync(new URL("../dist/", import.meta.url), { recursive: true });
writeFileSync(new URL("../dist/factory-engine.js", import.meta.url), code);
console.log(`dist/factory-engine.js: ${code.length} bytes, ${names.length} exports, sha256 ${createHash("sha256").update(code).digest("hex").slice(0, 16)}`);
